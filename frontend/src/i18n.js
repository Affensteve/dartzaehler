export function t(key, vars) {
  let s = (DICT[lang] && DICT[lang][key]) ?? DICT.de[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}

// Hook: liefert t() und rendert bei Sprachwechsel neu.
export function useT() {
  useLang();
  return t;
}

// Lokalisiertes Spiel-Label, z. B. "501, Double Out, Best of 3".
export function gameLabel({ mode, format, checkout } = {}) {
  const parts = [];
  if (mode) parts.push(String(mode));
  if (checkout === 'mixed') parts.push(t('out.mixed'));
  else if (checkout === 'single') parts.push(t('out.single'));
  else if (checkout === 'master') parts.push(t('out.master'));
  else if (checkout) parts.push(t('out.double'));
  if (format) {
    const f = format.satzLegMode;
    if (f === 'unlimited') parts.push(t('fmt.unlimited'));
    else if (f === 'bestof') parts.push(t('fmt.bestof', { n: format.legs }));
    else parts.push(t('fmt.firstto', { sets: format.sets, setWord: format.sets === 1 ? t('fmt.set1') : t('fmt.setN'), legs: format.legs }));
  }
  return parts.join(', ');
}
